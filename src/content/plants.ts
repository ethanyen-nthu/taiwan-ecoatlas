import type { Localized } from "@/lib/types";

/**
 * A short guide to the trees in Taipei's park and riverside inventories.
 *
 * The inventories give a Chinese name for every tree, and a scientific name
 * only for the riverside survey. This guide adds the scientific name, the
 * family, the kind of tree and where it comes from for the commonest species
 * (they cover most of the 95,000+ trees). Family names follow the Taiwan Flora
 * grouping used by the Taipei inventories; the newer APG IV system moves a few
 * (for example 茄苳 from Euphorbiaceae to Phyllanthaceae).
 */
export type PlantHabit = "evergreen" | "deciduous" | "palm" | "conifer";
export type PlantOrigin = "native" | "introduced";

export interface PlantInfo {
  sci: string;
  en: string;
  family: string;
  familyZh: string;
  habit: PlantHabit;
  /** Omitted when sources disagree or the plant is naturalised. */
  origin?: PlantOrigin;
  endemic?: boolean;
  note: Localized;
}

